-- =====================================================================
-- V6 - Histórico, versionamento e concorrência otimista (ADR-0007)
--
-- hist.* guarda um changelog completo: a imagem da linha após cada
-- INSERT/UPDATE e a imagem anterior em cada DELETE (tombstone).
-- Isso atende três necessidades com um único mecanismo:
--   1. auditoria (quem alterou, quando, o quê)
--   2. consulta "como era em uma data" (as-of)
--   3. feed de sincronização incremental para o app offline-first
-- =====================================================================

CREATE TABLE hist.ocorrencia (
    LIKE core.ocorrencia,
    hist_operacao      char(1)     NOT NULL CHECK (hist_operacao IN ('I', 'U', 'D')),
    hist_registrado_em timestamptz NOT NULL,
    hist_usuario       text        NOT NULL,
    hist_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE INDEX ix_hist_ocorrencia_chave ON hist.ocorrencia (chave_origem, hist_registrado_em);
CREATE INDEX ix_hist_ocorrencia_tempo ON hist.ocorrencia (hist_registrado_em);

COMMENT ON TABLE  hist.ocorrencia IS 'Changelog de core.ocorrencia. Mesmas colunas da tabela de origem, na mesma ordem, mais os metadados hist_*.';
COMMENT ON COLUMN hist.ocorrencia.hist_operacao IS 'I = inclusão, U = alteração, D = exclusão (imagem anterior à exclusão).';
COMMENT ON COLUMN hist.ocorrencia.hist_registrado_em IS 'Momento da operação (horário da transação).';
COMMENT ON COLUMN hist.ocorrencia.hist_usuario IS 'Papel de banco que executou a operação.';
COMMENT ON COLUMN hist.ocorrencia.hist_id IS 'Identificador sequencial do evento de histórico.';

CREATE TABLE hist.ocorrencia_dano (
    LIKE core.ocorrencia_dano,
    hist_operacao      char(1)     NOT NULL CHECK (hist_operacao IN ('I', 'U', 'D')),
    hist_registrado_em timestamptz NOT NULL,
    hist_usuario       text        NOT NULL,
    hist_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE INDEX ix_hist_dano_ocorrencia ON hist.ocorrencia_dano (id_ocorrencia, hist_registrado_em);

COMMENT ON TABLE hist.ocorrencia_dano IS 'Changelog de core.ocorrencia_dano.';
COMMENT ON COLUMN hist.ocorrencia_dano.hist_operacao IS 'I = inclusão, U = alteração, D = exclusão.';
COMMENT ON COLUMN hist.ocorrencia_dano.hist_registrado_em IS 'Momento da operação.';
COMMENT ON COLUMN hist.ocorrencia_dano.hist_usuario IS 'Papel de banco que executou a operação.';
COMMENT ON COLUMN hist.ocorrencia_dano.hist_id IS 'Identificador sequencial do evento de histórico.';

-- Gatilho genérico: grava a imagem da linha em hist.<mesma tabela>.
-- Depende de hist.<tabela> ter as colunas da origem primeiro e na mesma
-- ordem (garantido por LIKE e verificado em tests/sql/030_historico.sql).
CREATE FUNCTION hist.fn_registrar() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        EXECUTE format('INSERT INTO hist.%I SELECT ($1).*, $2, now(), $3', TG_TABLE_NAME)
            USING OLD, 'D', session_user;
        RETURN OLD;
    ELSE
        EXECUTE format('INSERT INTO hist.%I SELECT ($1).*, $2, now(), $3', TG_TABLE_NAME)
            USING NEW, left(TG_OP, 1), session_user;
        RETURN NEW;
    END IF;
END;
$$;

COMMENT ON FUNCTION hist.fn_registrar() IS 'Gatilho genérico de changelog para tabelas do core.';

CREATE TRIGGER tg_hist_ocorrencia
    AFTER INSERT OR UPDATE OR DELETE ON core.ocorrencia
    FOR EACH ROW EXECUTE FUNCTION hist.fn_registrar();

CREATE TRIGGER tg_hist_ocorrencia_dano
    AFTER INSERT OR UPDATE OR DELETE ON core.ocorrencia_dano
    FOR EACH ROW EXECUTE FUNCTION hist.fn_registrar();

-- Versionamento e concorrência otimista.
-- Quem atualiza informa a versão que leu (ou não informa nada).
-- Se informar uma versão diferente da atual, a alteração é recusada:
-- outro processo alterou o registro nesse meio-tempo.
CREATE FUNCTION core.fn_versionar_ocorrencia() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.versao <> OLD.versao THEN
        RAISE EXCEPTION 'Conflito de versão na ocorrência %: versão informada %, versão atual %',
                        OLD.chave_origem, NEW.versao, OLD.versao
            USING ERRCODE = 'serialization_failure',
                  HINT = 'Releia o registro e reaplique a alteração.';
    END IF;
    NEW.id_ocorrencia := OLD.id_ocorrencia;
    NEW.chave_origem  := OLD.chave_origem;
    NEW.criado_em     := OLD.criado_em;
    NEW.versao        := OLD.versao + 1;
    NEW.atualizado_em := now();
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION core.fn_versionar_ocorrencia() IS 'Incrementa versão, atualiza carimbo de tempo, protege campos imutáveis e recusa atualização com versão desatualizada.';

CREATE TRIGGER tg_versionar_ocorrencia
    BEFORE UPDATE ON core.ocorrencia
    FOR EACH ROW
    WHEN (OLD IS DISTINCT FROM NEW)
    EXECUTE FUNCTION core.fn_versionar_ocorrencia();

-- Alteração em danos também é alteração da ocorrência (para auditoria
-- e para a sincronização incremental perceber a mudança).
CREATE FUNCTION core.fn_tocar_ocorrencia_por_dano() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE core.ocorrencia
       SET atualizado_em = now()
     WHERE id_ocorrencia = COALESCE(NEW.id_ocorrencia, OLD.id_ocorrencia)
       AND atualizado_em < now();
    RETURN NULL;
END;
$$;

COMMENT ON FUNCTION core.fn_tocar_ocorrencia_por_dano() IS 'Propaga alteração de dano para a ocorrência (nova versão), no máximo uma vez por transação.';

CREATE TRIGGER tg_dano_toca_ocorrencia
    AFTER INSERT OR UPDATE OR DELETE ON core.ocorrencia_dano
    FOR EACH ROW EXECUTE FUNCTION core.fn_tocar_ocorrencia_por_dano();

-- Consulta "como era em uma data".
CREATE FUNCTION hist.fn_ocorrencia_em(p_chave_origem text, p_momento timestamptz)
RETURNS jsonb
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN h.hist_operacao = 'D' THEN NULL
                ELSE to_jsonb(h) - 'hist_id' END
    FROM hist.ocorrencia h
    WHERE h.chave_origem = p_chave_origem
      AND h.hist_registrado_em <= p_momento
    ORDER BY h.hist_registrado_em DESC, h.hist_id DESC
    LIMIT 1;
$$;

COMMENT ON FUNCTION hist.fn_ocorrencia_em(text, timestamptz) IS 'Retorna a ocorrência como estava no momento informado (NULL se não existia ou já havia sido excluída).';
